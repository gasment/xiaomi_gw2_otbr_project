"""Fetch locked HTTP dependencies and embed the frozen frontend; never builds."""
from pathlib import Path
import gzip
import subprocess
import sys

root = Path(__file__).resolve().parents[1]
repo = root / 'vendor/ot-br-posix'
pins = {
    'third_party/cJSON/repo': 'cf97c6f066d81fdbba4ef722cfd327bbbba2365c',
    'third_party/cpp-httplib/repo': '03cf43ebaa55f27a2778bed870ea3549f7e84e2c',
}
verify = '--verify' in sys.argv
for relative, commit in pins.items():
    path = repo / relative
    if not (path / '.git').exists():
        if verify:
            raise SystemExit('Missing Web dependency; run sh prepare-web.sh')
        subprocess.run(['git', '-C', str(repo), 'submodule', 'update', '--init', '--depth', '1', '--', relative], check=True)
    actual = subprocess.check_output(['git', '-C', str(path), 'rev-parse', 'HEAD'], text=True).strip()
    if actual != commit:
        raise SystemExit('Unexpected Web dependency revision: ' + relative)
    dirty = subprocess.check_output(['git', '-C', str(path), 'status', '--porcelain', '--untracked-files=no'], text=True)
    if dirty.strip():
        raise SystemExit('Web dependency has local edits: ' + relative)
types = {'.html': 'text/html; charset=utf-8', '.js': 'application/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.ico': 'image/x-icon', '.png': 'image/png'}
lines = ['// Generated by tools/prepare_web.py; frontend provenance: web/SOURCE.md.', '#pragma once', '#include <cstddef>', 'namespace otbr_host {', 'struct WebAsset { const char *path; const char *type; const unsigned char *data; std::size_t size; };']
entries = []
assets = sorted(path for path in (root / 'web/frontend').rglob('*')
                if path.is_file() and not path.name.endswith(':Zone.Identifier'))
for i, path in enumerate(assets):
    data = gzip.compress(path.read_bytes(), mtime=0)
    name = 'asset_' + str(i)
    lines.append('inline constexpr unsigned char ' + name + '[] = {')
    lines.extend(','.join(str(n) for n in data[j:j+32]) + ',' for j in range(0, len(data), 32))
    lines.append('};')
    relative = '/' + path.relative_to(root / 'web/frontend').as_posix()
    entries.append('{"%s","%s",%s,sizeof(%s)}' % (relative, types[path.suffix], name, name))
lines.append('inline constexpr WebAsset web_assets[] = {' + ',\n'.join(entries) + '};\n}')
output = root / 'web/generated/web_assets.hpp'
if not verify:
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines) + '\n')
elif not output.is_file() or output.read_text() != '\n'.join(lines) + '\n':
    raise SystemExit('Embedded frontend out of date; run sh prepare-web.sh')
print('WEB_DEPS_ASSETS_READY. No compilation or gateway operation.')
